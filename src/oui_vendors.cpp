const char* oui_vendor(uint32_t oui) {
    size_t lo = 0, hi = OUI_COUNT;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (OUI_TABLE[mid].oui < oui) lo = mid + 1;
        else hi = mid;
    }
    if (lo < OUI_COUNT && OUI_TABLE[lo].oui == oui) return OUI_TABLE[lo].vendor;
    return nullptr;
}

// Parses "AA:BB:CC:..." (locally-administered bit ignored) into a 24-bit OUI.
const char* oui_vendor_from_bssid(const char* bssidStr) {
    if (!bssidStr) return nullptr;
    uint32_t oui = 0;
    int nibbles = 0;
    for (const char* p = bssidStr; *p && nibbles < 6; ++p) {
        char c = *p;
        int v;
        if (c >= '0' && c <= '9') v = c - '0';
        else if (c >= 'a' && c <= 'f') v = c - 'a' + 10;
        else if (c >= 'A' && c <= 'F') v = c - 'A' + 10;
        else continue; // skip ':' separators
        oui = (oui << 4) | v;
        ++nibbles;
    }
    if (nibbles < 6) return nullptr;
    return oui_vendor(oui);
}
